import { ProductError } from './access.js';
import type { ProductModule } from './module.js';

const workflowStatusReasons = new Map([
  ['This phase has not started; its specialist runtime or approval capabilities are not yet connected.', 'specialist-unavailable'],
  ['This phase has not started; the candidate, passing QA evidence or release inputs need attention.', 'release-inputs-unavailable'],
  ['This phase has not started; its protected QA candidate or workspace is unavailable.', 'protected-workspace-unavailable'],
  ['The specialist turn did not return a confirmed structured result.', 'specialist-result-unconfirmed'],
  ['The specialist returned an invalid result.', 'specialist-result-invalid'],
  ['The specialist turn was already started and must be reconciled.', 'specialist-result-unconfirmed'],
  ['The phase result was not confirmed.', 'phase-result-unconfirmed'],
  ['The phase could not be reconciled.', 'phase-reconciliation-unavailable'],
  ['The staging receipt is not confirmed; reconcile the release before continuing.', 'release-reconciliation'],
  ['The staging receipt is recorded, but post-deployment verification is not confirmed.', 'release-verification'],
  ['The disposable staging target is not configured.', 'release-target-unavailable'],
  ['The approved target is not the configured staging target.', 'release-target-mismatch'],
  ['The staging effect is still uncertain; reconcile it before continuing.', 'release-reconciliation'],
  ['The deployment was already started; reconcile it before continuing.', 'release-reconciliation'],
  ['The deployment has a prior operation; reconcile it before continuing.', 'release-reconciliation'],
  ['The staging effect was not confirmed; reconcile it before continuing.', 'release-reconciliation'],
  ['The approved deployment could not be confirmed; reconcile it before continuing.', 'release-reconciliation'],
  ['The approved deployment could not be reconciled.', 'release-reconciliation'],
  ['The release was rejected by the approver.', 'release-rejected'],
  ['The outcome referenced a phase outside the pinned plan.', 'workflow-plan-invalid'],
  ['The workflow exceeded its phase limit.', 'workflow-phase-limit'],
]);

function safeWorkflowReason(state: string, reason: unknown) {
  if (typeof reason !== 'string') return undefined;
  if (state === 'uncertain') return workflowStatusReasons.get(reason);
  if (state !== 'blocked') return undefined;
  const blockedReasons = new Map([
    ['The release was rejected by the approver.', 'release-rejected'],
    ['The outcome referenced a phase outside the pinned plan.', 'workflow-plan-invalid'],
    ['The workflow exceeded its phase limit.', 'workflow-phase-limit'],
  ]);
  const blocked = blockedReasons.get(reason);
  if (blocked) return blocked;
  // This sentence is generated by the server from the bounded retry counter;
  // arbitrary specialist-provided failure details are intentionally excluded.
  if (state === 'blocked' && /^The specialist failed after [1-9][0-9]{0,2} attempts?\.$/.test(reason)) return 'specialist-retries-exhausted';
  return undefined;
}

/** Deliver a durable wake-up only while the original work remains authorized. */
export async function dispatchPendingReconciliation(module: ProductModule) {
  const endpoint = process.env.WORKFLOW_ENGINE_URL, token = process.env.WORKFLOW_ENGINE_TOKEN;
  if (!endpoint || !token || token.length < 32) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine is not configured.');
  let url: URL;
  try { url = new URL(endpoint); } catch { throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.'); }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.');
  let attempted: { projectId: string; runId: string; occurrenceId: string; conflictId: string } | undefined;
  try {
    return await module.database.begin(async tx => {
      const [row] = await tx.unsafe<{ projectId: string; runId: string; occurrenceId: string; conflictId: string; installationId: string }>(`
        select i.project_id as "projectId",i.run_id as "runId",i.occurrence_id as "occurrenceId",i.conflict_id as "conflictId",p.installation_id as "installationId"
        from bp_reconciliation_intents i
        join bp_phase_occurrences o on (o.project_id,o.run_id,o.id)=(i.project_id,i.run_id,i.occurrence_id)
        join bp_workflow_runs r on (r.project_id,r.id)=(i.project_id,i.run_id)
        join bp_work_items w on (w.project_id,w.id)=(r.project_id,r.work_item_id)
        join bp_projects p on p.id=r.project_id
        join bp_memberships m on m.project_id=p.id and m.user_id=w.requested_by
        join bp_conversations c on c.project_id=w.project_id and c.native_channel_id=w.native_channel_id
        join channel_memberships cm on cm.channel_id=c.native_channel_id and cm.user_id=w.requested_by
        join channels ch on ch.id=c.native_channel_id and ch.deleted_at is null
        join bp_assignments a on (a.project_id,a.id)=(o.project_id,o.assignment_id)
        where i.state='Pending' and i.next_attempt_at<=now() and r.state='Running' and r.current_phase=o.phase_key and p.state='Operational'
          and 'read'=any(m.permissions) and 'work'=any(m.permissions)
          and not exists(select 1 from bp_memory_conflicts x where x.project_id=a.project_id and x.assignment_id=a.id and x.state='Pending')
        order by i.created_at,i.project_id,i.run_id limit 1 for update of i skip locked for share of o,r,w,p,m,c,cm,ch,a`);
      if (!row) return false;
      attempted = row;
      const response = await fetch(new URL('/reconcile', url), { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(15000),
        headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
        body: JSON.stringify({ run: { installationId: row.installationId, projectId: row.projectId, runId: row.runId } }) });
      const result = await response.json().catch(() => null) as { accepted?: unknown } | null;
      if (!response.ok || result?.accepted !== true) throw new ProductError(409, 'workflow_unavailable', 'The workflow engine did not confirm reconciliation.');
      await tx.unsafe(`update bp_reconciliation_intents set state='Sent',sent_at=now()
        where project_id=$1 and run_id=$2 and occurrence_id=$3 and conflict_id=$4 and state='Pending'`, [row.projectId,row.runId,row.occurrenceId,row.conflictId]);
      return true;
    });
  } catch (error) {
    if (attempted) await module.database.unsafe(`update bp_reconciliation_intents set failures=failures+1,next_attempt_at=now()+interval '30 seconds'
      where project_id=$1 and run_id=$2 and occurrence_id=$3 and conflict_id=$4 and state='Pending'`, [attempted.projectId,attempted.runId,attempted.occurrenceId,attempted.conflictId]);
    throw error;
  }
}

/** Request recovery for the original requester's still-authorized work. */
export async function reconcileWorkflow(module: ProductModule, actor: import('./access.js').ProductActor,
  projectId: string, workItemId: string, runId: string) {
  const endpoint = process.env.WORKFLOW_ENGINE_URL, token = process.env.WORKFLOW_ENGINE_TOKEN;
  if (!endpoint || !token || token.length < 32) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine is not configured.');
  let url: URL;
  try { url = new URL(endpoint); } catch { throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.'); }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.');
  return module.database.begin(async tx => {
    const { requireProject, requireOperational } = await import('./access.js');
    const project = await requireProject(tx, actor, projectId, 'work');
    requireOperational(project);
    const [run] = await tx.unsafe<{ installationId: string }>(`select p.installation_id as "installationId"
      from bp_workflow_runs r join bp_work_items w on (w.project_id,w.id)=(r.project_id,r.work_item_id)
      join bp_projects p on p.id=r.project_id
      join bp_conversations c on c.project_id=w.project_id and c.native_channel_id=w.native_channel_id
      join channel_memberships cm on cm.channel_id=c.native_channel_id and cm.user_id=$4
      join channels ch on ch.id=c.native_channel_id and ch.deleted_at is null
      where r.project_id=$1 and w.id=$2 and r.id=$3 and w.requested_by=$4 and r.state='Running'
      for share of r,w,p,c,cm,ch`, [projectId,workItemId,runId,actor.id]);
    if (!run) throw new ProductError(404, 'work_item_not_found', 'Work item not found.');
    let response: Response;
    try {
      response = await fetch(new URL('/reconcile', url), { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(15000),
        headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
        body: JSON.stringify({ run: { installationId: run.installationId, projectId, runId } }) });
    } catch { throw new ProductError(409, 'workflow_unavailable', 'The workflow engine could not be reached. Try again.'); }
    const result = await response.json().catch(() => null) as { accepted?: unknown } | null;
    if (!response.ok || result?.accepted !== true) throw new ProductError(409, 'reconciliation_unavailable', 'This run is not awaiting recovery, or recovery is temporarily unavailable.');
    return { accepted: true };
  });
}

/** Return only the engine state to the original requester, after rechecking access. */
export async function readWorkflowEngineState(module: ProductModule, actor: import('./access.js').ProductActor,
  projectId: string, workItemId: string, runId: string) {
  const endpoint = process.env.WORKFLOW_ENGINE_URL, token = process.env.WORKFLOW_ENGINE_TOKEN;
  if (!endpoint || !token || token.length < 32) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine is not configured.');
  let url: URL;
  try { url = new URL(endpoint); } catch { throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.'); }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) throw new ProductError(409, 'workflow_unconfigured', 'The workflow engine address is invalid.');
  return module.database.begin(async tx => {
    const { requireProject } = await import('./access.js');
    await requireProject(tx, actor, projectId, 'work');
    const [run] = await tx.unsafe<{ installationId: string }>(`select p.installation_id as "installationId"
      from bp_workflow_runs r join bp_work_items w on (w.project_id,w.id)=(r.project_id,r.work_item_id)
      join bp_projects p on p.id=r.project_id
      join bp_conversations c on c.project_id=w.project_id and c.native_channel_id=w.native_channel_id
      join channel_memberships cm on cm.channel_id=c.native_channel_id and cm.user_id=$4
      join channels ch on ch.id=c.native_channel_id and ch.deleted_at is null
      where r.project_id=$1 and w.id=$2 and r.id=$3 and w.requested_by=$4 and r.state='Running'
      for share of r,w,p,c,cm,ch`, [projectId,workItemId,runId,actor.id]);
    if (!run) throw new ProductError(404, 'work_item_not_found', 'Work item not found.');
    let response: Response;
    try { response = await fetch(new URL('/status', url), { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(5000),
      headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
      body: JSON.stringify({ run: { installationId: run.installationId, projectId, runId } }) }); }
    catch { throw new ProductError(409, 'workflow_unavailable', 'Workflow status is unavailable.'); }
    const result = await response.json().catch(() => null) as { snapshot?: { state?: unknown; reason?: unknown } } | null;
    const state = result?.snapshot?.state;
    if (!response.ok || typeof state !== 'string' || !['running','waiting','uncertain','blocked','complete'].includes(state)) {
      throw new ProductError(409, 'workflow_unavailable', 'Workflow status is unavailable.');
    }
    // Engine reasons can contain restricted artifact data or arbitrary model
    // output. Only translate exact server-owned messages; never relay raw text.
    const reasonCode = safeWorkflowReason(state, result?.snapshot?.reason);
    if (!reasonCode) return { state };
    // Even a category can reveal something about a restricted input. Only
    // disclose it when every artifact referenced by this run is still visible.
    const [visibility] = await tx.unsafe<{ visible: boolean }>(`select
      exists(select 1 from bp_action_attempts a where a.project_id=$1 and a.run_id=$2)
      and not exists (select 1 from bp_action_attempts a,
        jsonb_array_elements(a.input_revisions || a.output_revisions) ref
        where a.project_id=$1 and a.run_id=$2 and not exists (
          select 1 from bp_artifact_revisions ar join bp_artifacts artifact
            on (artifact.project_id,artifact.id)=(ar.project_id,ar.artifact_id)
          where ar.project_id=a.project_id and ar.id=ref->>'revisionId'
            and artifact.type_key=ref->>'type' and artifact.status='supplied'
            and (artifact.allowed_user_ids is null or $3=any(artifact.allowed_user_ids)))) as visible`, [projectId,runId,actor.id]);
    return { state, ...(visibility?.visible ? { reasonCode } : {}) };
  });
}
